"""Generate a PostgreSQL schema script from the Alembic migrations.

The migrations remain the source of truth. This script renders them in offline
mode, without connecting to a database, so the output can be reviewed, pasted
into the Neon SQL Editor or committed as ``sql/assetlens_schema.sql``.
"""

from __future__ import annotations

import sys

from alembic import command
from alembic.config import Config

from assetlens.config import project_root

# Offline mode only uses the dialect, so the host and credentials are never
# contacted. Keeping them fake makes it obvious that this is not a real secret.
OFFLINE_URL = "postgresql+psycopg://user:password@localhost/assetlens"

HEADER = """-- Generated by `make db-sql` from the Alembic migrations.
-- Do not edit by hand; edit the migrations and regenerate.

"""


def main() -> None:
    """Write the full schema as PostgreSQL DDL to standard output."""

    root = project_root()
    config = Config(str(root / "alembic.ini"))
    config.set_main_option("script_location", str(root / "migrations"))
    config.set_main_option("sqlalchemy.url", OFFLINE_URL)

    sys.stdout.write(HEADER)
    command.upgrade(config, "head", sql=True)


if __name__ == "__main__":
    main()
