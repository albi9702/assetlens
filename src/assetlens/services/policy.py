"""Life-insurance policy analytics.

The module is deliberately pure: it never touches the database. It turns a
premium schedule and a set of holdings into one snapshot containing the gross
value, the Italian substitute tax and the money-weighted return (TIR/XIRR).

The Italian tax rule used here is the ordinary one for life policies: 20% of
the capital gain, where the gain is ``gross value - premiums paid`` and a loss
is not taxed (and not refunded). A 12.5% rate applies to the share of the
return generated by government bonds; that refinement needs the insurer's
breakdown and is therefore left to the caller through ``tax_rate``.
"""

from __future__ import annotations

from collections.abc import Sequence
from dataclasses import asdict, dataclass
from datetime import date
from typing import Any

DEFAULT_TAX_RATE = 0.20
DAYS_PER_YEAR = 365.25
MAX_ITERATIONS = 200
TOLERANCE = 1e-10
MIN_RATE = -0.9999
MAX_RATE = 10.0


@dataclass(frozen=True, slots=True)
class Premium:
    """A single premium payment."""

    paid_on: date
    amount: float


@dataclass(frozen=True, slots=True)
class Holding:
    """One compartment of the policy.

    Separate accounts (GESAV) have no quotes; unit-linked compartments carry a
    number of quotes and a NAV. ``value`` is always the euro countervalue and
    is the only field used by the calculations.
    """

    name: str
    value: float
    quote: float | None = None
    nav: float | None = None

    @property
    def is_separate_account(self) -> bool:
        return self.quote is None


@dataclass(frozen=True, slots=True)
class PremiumTranche:
    """One premium projected to the valuation date.

    ``projected_value`` is the part of the policy value that the TIR attributes
    to this premium: growing every premium at the same annual rate makes the
    projected values add up to the policy value.
    """

    paid_on: date
    amount: float
    years_invested: float
    weight_pct: float
    projected_value: float
    gain: float
    value_weight_pct: float


@dataclass(frozen=True, slots=True)
class PolicySummary:
    """Everything needed to persist and display a policy snapshot."""

    as_of: date
    currency: str
    total_premiums: float
    gesav_value: float
    funds_value: float
    gross_value: float
    capital_gain: float
    tax_rate: float
    tax_amount: float
    net_value: float
    gross_irr_pct: float | None
    net_irr_pct: float | None
    premiums: tuple[Premium, ...]
    holdings: tuple[Holding, ...]

    def as_dict(self) -> dict[str, Any]:
        """Return a JSON-friendly mapping (dates are left to the caller)."""

        return asdict(self)

    def premiums_json(self) -> list[dict[str, Any]]:
        return [
            {"paid_on": premium.paid_on.isoformat(), "amount": premium.amount}
            for premium in self.premiums
        ]

    def holdings_json(self) -> list[dict[str, Any]]:
        return [
            {
                "name": holding.name,
                "quote": holding.quote,
                "nav": holding.nav,
                "value": holding.value,
            }
            for holding in self.holdings
        ]


def _npv(rate: float, flows: Sequence[tuple[date, float]], origin: date) -> float:
    """Net present value of dated cash flows at an annual rate."""

    return sum(
        amount / (1.0 + rate) ** ((day - origin).days / DAYS_PER_YEAR) for day, amount in flows
    )


def xirr(
    flows: Sequence[tuple[date, float]],
    *,
    low: float = MIN_RATE,
    high: float = MAX_RATE,
) -> float | None:
    """Return the annualised money-weighted return (TIR), or ``None``.

    The function solves ``NPV(rate) = 0`` by bisection. It returns ``None``
    when the flows do not contain both a negative and a positive amount, or
    when no root exists in the bracket.
    """

    if not flows:
        return None

    ordered = sorted(flows)
    if not (any(amount < 0 for _, amount in ordered) and any(amount > 0 for _, amount in ordered)):
        return None

    origin = ordered[0][0]
    f_low = _npv(low, ordered, origin)
    f_high = _npv(high, ordered, origin)
    if f_low * f_high > 0:
        return None

    for _ in range(MAX_ITERATIONS):
        mid = (low + high) / 2.0
        f_mid = _npv(mid, ordered, origin)
        if abs(f_mid) < TOLERANCE:
            return mid
        if f_low * f_mid <= 0:
            high = mid
        else:
            low = mid
            f_low = f_mid

    return (low + high) / 2.0


def compute_policy_summary(
    premiums: Sequence[Premium],
    holdings: Sequence[Holding],
    *,
    as_of: date,
    currency: str = "EUR",
    tax_rate: float = DEFAULT_TAX_RATE,
) -> PolicySummary:
    """Build a :class:`PolicySummary` from a premium schedule and holdings."""

    if not premiums:
        raise ValueError("at least one premium is required")
    if not holdings:
        raise ValueError("at least one holding is required")
    if not 0.0 <= tax_rate <= 1.0:
        raise ValueError("tax_rate must be between 0 and 1")
    if any(premium.amount <= 0 for premium in premiums):
        raise ValueError("premium amounts must be positive")
    if any(holding.value < 0 for holding in holdings):
        raise ValueError("holding values cannot be negative")
    if as_of < max(premium.paid_on for premium in premiums):
        raise ValueError("as_of cannot be before the last premium")

    ordered_premiums = tuple(sorted(premiums, key=lambda premium: premium.paid_on))
    ordered_holdings = tuple(holdings)

    total_premiums = round(sum(premium.amount for premium in ordered_premiums), 2)
    gesav_value = round(
        sum(holding.value for holding in ordered_holdings if holding.is_separate_account), 2
    )
    funds_value = round(
        sum(holding.value for holding in ordered_holdings if not holding.is_separate_account), 2
    )
    gross_value = round(gesav_value + funds_value, 2)
    capital_gain = round(gross_value - total_premiums, 2)
    tax_amount = round(max(capital_gain, 0.0) * tax_rate, 2)
    net_value = round(gross_value - tax_amount, 2)

    gross_flows = [(premium.paid_on, -premium.amount) for premium in ordered_premiums]
    gross_flows.append((as_of, gross_value))
    gross_irr = xirr(gross_flows)

    net_flows = [(premium.paid_on, -premium.amount) for premium in ordered_premiums]
    net_flows.append((as_of, net_value))
    net_irr = xirr(net_flows)

    return PolicySummary(
        as_of=as_of,
        currency=currency.upper(),
        total_premiums=total_premiums,
        gesav_value=gesav_value,
        funds_value=funds_value,
        gross_value=gross_value,
        capital_gain=capital_gain,
        tax_rate=tax_rate,
        tax_amount=tax_amount,
        net_value=net_value,
        gross_irr_pct=round(gross_irr * 100.0, 6) if gross_irr is not None else None,
        net_irr_pct=round(net_irr * 100.0, 6) if net_irr is not None else None,
        premiums=ordered_premiums,
        holdings=ordered_holdings,
    )


def compute_premium_tranches(
    premiums: Sequence[Premium],
    *,
    as_of: date,
    annual_rate: float,
) -> tuple[PremiumTranche, ...]:
    """Split the policy value across the premiums that generated it.

    Each premium is projected to ``as_of`` with ``annual_rate`` (a fraction,
    not a percentage). Passing the policy TIR makes the projected values sum to
    the policy value, so ``projected_value`` is an exact attribution of the
    current value to each premium.

    The result also carries the two weights a chart usually needs:

    * ``weight_pct`` - the premium's share of the capital paid in;
    * ``value_weight_pct`` - the premium's share of the current value.
    """

    if not premiums:
        raise ValueError("at least one premium is required")
    if annual_rate <= -1.0:
        raise ValueError("annual_rate must be greater than -1")
    if as_of < max(premium.paid_on for premium in premiums):
        raise ValueError("as_of cannot be before the last premium")

    ordered = sorted(premiums, key=lambda premium: premium.paid_on)
    total_paid = sum(premium.amount for premium in ordered)
    if total_paid <= 0:
        raise ValueError("premium amounts must be positive")

    projections = [
        (
            premium,
            (as_of - premium.paid_on).days / DAYS_PER_YEAR,
            premium.amount
            * (1.0 + annual_rate) ** ((as_of - premium.paid_on).days / DAYS_PER_YEAR),
        )
        for premium in ordered
    ]
    total_value = sum(projected for _, _, projected in projections)

    return tuple(
        PremiumTranche(
            paid_on=premium.paid_on,
            amount=premium.amount,
            years_invested=round(years, 6),
            weight_pct=round(premium.amount / total_paid * 100.0, 6),
            projected_value=round(projected, 2),
            gain=round(projected - premium.amount, 2),
            value_weight_pct=round(projected / total_value * 100.0, 6) if total_value else 0.0,
        )
        for premium, years, projected in projections
    )
